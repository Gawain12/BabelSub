package ass

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/Gawain12/BabelSub/pkg/config"
)

type SubtitleEntry struct {
	Index int
	Start time.Duration
	End   time.Duration
	Text  string
}

func ParseSRT(filePath string) ([]SubtitleEntry, error) {
	file, err := os.Open(filePath)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	scanner.Buffer(make([]byte, 64*1024), 1<<20)
	var entries []SubtitleEntry

	var curEntry *SubtitleEntry
	var lines []string

	first := true
	for scanner.Scan() {
		raw := scanner.Text()
		if first {
			raw = strings.TrimPrefix(raw, "\uFEFF")
			first = false
		}
		line := strings.TrimSpace(raw)
		if line == "" {
			if curEntry != nil && len(lines) > 0 {
				curEntry.Text = strings.Join(lines, " ")
				entries = append(entries, *curEntry)
				curEntry = nil
				lines = nil
			}
			continue
		}

		if curEntry == nil {
			matches := timeRegex.FindStringSubmatch(line)
			if len(matches) == 9 {
				start := parseTime(matches[1], matches[2], matches[3], matches[4])
				end := parseTime(matches[5], matches[6], matches[7], matches[8])
				curEntry = &SubtitleEntry{Start: start, End: end}
				continue
			}
			if _, err := strconv.Atoi(line); err == nil {
				continue
			}
		} else {
			if clean := cleanText(line); clean != "" {
				lines = append(lines, clean)
			}
		}
	}

	if curEntry != nil && len(lines) > 0 {
		curEntry.Text = strings.Join(lines, " ")
		entries = append(entries, *curEntry)
	}

	return entries, nil
}

var (
	timeRegex     = regexp.MustCompile(`(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})\s*-->\s*(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})`)
	htmlTagRegex  = regexp.MustCompile(`</?[a-zA-Z][^>]*>`)
	assBlockRegex = regexp.MustCompile(`\{[^}]*\}`)
)

// cleanText strips HTML-ish tags and inline ASS override blocks so styles from
// the source files do not leak into the bilingual layout.
func cleanText(s string) string {
	s = htmlTagRegex.ReplaceAllString(s, "")
	s = assBlockRegex.ReplaceAllString(s, "")
	s = strings.ReplaceAll(s, "\\N", " ")
	s = strings.ReplaceAll(s, "\\n", " ")
	return strings.TrimSpace(s)
}

func parseTime(h, m, s, ms string) time.Duration {
	hours, _ := strconv.Atoi(h)
	mins, _ := strconv.Atoi(m)
	secs, _ := strconv.Atoi(s)
	for len(ms) < 3 {
		ms += "0"
	}
	milli, _ := strconv.Atoi(ms)
	return time.Duration(hours)*time.Hour +
		time.Duration(mins)*time.Minute +
		time.Duration(secs)*time.Second +
		time.Duration(milli)*time.Millisecond
}

func formatASSTime(d time.Duration) string {
	h := int(d.Hours())
	m := int(d.Minutes()) % 60
	s := int(d.Seconds()) % 60
	cs := int(d.Milliseconds()%1000) / 10
	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, s, cs)
}

func GenerateBilingualASS(primarySRT, secondarySRT, outPath string, style *config.StyleConfig) error {
	if style == nil {
		style = &config.DefaultConfig().Styling
	}

	prim, err := ParseSRT(primarySRT)
	if err != nil {
		return fmt.Errorf("failed to parse primary SRT: %w", err)
	}
	sec, err := ParseSRT(secondarySRT)
	if err != nil {
		return fmt.Errorf("failed to parse secondary SRT: %w", err)
	}
	if len(prim) == 0 {
		return fmt.Errorf("原语字幕没有解析出任何条目")
	}
	if len(sec) == 0 {
		return fmt.Errorf("中文字幕没有解析出任何条目")
	}
	st := *style
	style = &st
	if style.SecondaryFontSize <= 0 {
		style.SecondaryFontSize = style.PrimaryFontSize * 2 / 3
	}

	outFile, err := os.Create(outPath)
	if err != nil {
		return err
	}
	defer outFile.Close()

	w := bufio.NewWriter(outFile)

	// Note: Explicit PlayResX/PlayResY to guarantee correct non-stretched font scale across players like Infuse
	header := fmt.Sprintf(`[Script Info]
Title: BabelSub Bilingual Subtitle (Language Learning Edition)
; Generated by BabelSub: https://github.com/Gawain12/BabelSub
; Notice: Automatically aligned/generated for language acquisition purposes.
; Content may contain occasional discrepancies or timing variances. Please use as study reference.
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601
PlayResX: %d
PlayResY: %d

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,%s,%d,%s,&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2.0,1.0,2,30,30,%d,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`,
		style.PlayResX,
		style.PlayResY,
		style.FontName,
		style.PrimaryFontSize,
		style.PrimaryColor,
		style.MarginV,
	)
	w.WriteString(header)

	secTag := fmt.Sprintf("{\\fs%d\\c%s}", style.SecondaryFontSize, style.SecondaryColor)
	used := make([]bool, len(sec))
	var events []event

	for _, p := range prim {
		var matchedSec []string
		for i, s := range sec {
			if s.End <= p.Start || s.Start >= p.End {
				continue
			}
			overlap := minDur(p.End, s.End) - maxDur(p.Start, s.Start)
			shortest := minDur(p.End-p.Start, s.End-s.Start)
			// Require a meaningful overlap so a line is not attached to two neighbours.
			if shortest > 0 && overlap*3 < shortest {
				continue
			}
			used[i] = true
			if clean := strings.TrimSpace(s.Text); clean != "" {
				matchedSec = append(matchedSec, clean)
			}
		}

		text := p.Text
		if len(matchedSec) > 0 {
			text = fmt.Sprintf("%s\\N%s%s", p.Text, secTag, strings.Join(matchedSec, " "))
		}
		events = append(events, event{p.Start, p.End, text})
	}

	// Keep translated-only lines (signs, songs) that have no counterpart.
	for i, s := range sec {
		if !used[i] && strings.TrimSpace(s.Text) != "" {
			events = append(events, event{s.Start, s.End, secTag + s.Text})
		}
	}
	sort.SliceStable(events, func(i, j int) bool { return events[i].start < events[j].start })

	for _, e := range events {
		fmt.Fprintf(w, "Dialogue: 0,%s,%s,Default,,0,0,0,,%s\n", formatASSTime(e.start), formatASSTime(e.end), e.text)
	}

	return w.Flush()
}

type event struct {
	start, end time.Duration
	text       string
}

func minDur(a, b time.Duration) time.Duration {
	if a < b {
		return a
	}
	return b
}

func maxDur(a, b time.Duration) time.Duration {
	if a > b {
		return a
	}
	return b
}
